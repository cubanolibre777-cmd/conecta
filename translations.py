def t(key, lang=None, **kwargs):
    """Devuelve el texto traducido para `key` en el idioma `lang`.

    Si falta la clave en ese idioma, cae a español. Si tampoco existe en
    español, devuelve la propia clave entre corchetes (para detectar
    fácilmente textos sin traducir durante el desarrollo).
    """
    lang = lang if lang in TRANSLATIONS else DEFAULT_LANGUAGE
    text = TRANSLATIONS.get(lang, {}).get(key)
    if text is None:
        text = TRANSLATIONS[DEFAULT_LANGUAGE].get(key, f"[{key}]")
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError):
            return text
    return text


def detect_language_from_request(accept_languages, default=DEFAULT_LANGUAGE):
    """Recibe request.accept_languages (Flask/Werkzeug) y devuelve el mejor
    idioma soportado, o `default` si no hay coincidencia."""
    best = accept_languages.best_match(SUPPORTED_LANGUAGES)
    return best or default
